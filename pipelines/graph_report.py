"""reports/graph_report.html: human-review page for the generated graph (brief §9A step 6).

Self-contained except Leaflet from unpkg (pinned version) and OSM raster tiles (dev/demo use only, with
attribution). Shows counts per node type, drops, validation checks, speed-source breakdown, a map with
flagged nodes, and an ETA sanity table that is explicitly labelled as model output.
"""
from __future__ import annotations

import html
import json

import pandas as pd

from pipelines.common import ROOT

LEAFLET = "https://unpkg.com/leaflet@1.9.4/dist"
SANITY_PAIRS = [("Nagpur", "Wardha"), ("Nagpur", "Chandrapur"), ("Nagpur", "Bhandara"), ("Nagpur", "Gondia"),
                ("Chandrapur", "Gadchiroli"), ("Wardha", "Chandrapur")]


def _table(df: pd.DataFrame) -> str:
    return df.to_html(index=False, escape=True, border=0, classes="t", na_rep="")


def sanity_table(nodes: pd.DataFrame, od: pd.DataFrame) -> pd.DataFrame:
    """District-HQ market pairs: uses the 'APMC <District>' market of each district when it is routable."""
    rows = []
    usable = nodes[~nodes["needs_review"]]
    for a, b in SANITY_PAIRS:
        def pick(d):
            m = usable[(usable["district"] == d) & usable["name"].str.fullmatch(rf"APMC {d}|{d}.*", case=False)
                       & usable["node_type"].isin(["ReceivingMarket", "AssemblyMandi"])]
            return m.iloc[0] if len(m) else None
        o, t = pick(a), pick(b)
        if o is None or t is None:
            rows.append({"from": a, "to": b, "road_km": None, "free_flow_h": None, "note": "market not routable (needs review)"})
            continue
        hit = od[(od["origin"] == o["node_id"]) & (od["dest"] == t["node_id"])]
        rows.append({"from": f"{o['name']}", "to": f"{t['name']}",
                     "road_km": round(hit["dist_m"].iloc[0] / 1000, 1) if len(hit) else None,
                     "free_flow_h": round(hit["time_s"].iloc[0] / 3600, 2) if len(hit) else None,
                     "note": "model output, NOT a verified travel time"})
    return pd.DataFrame(rows)


