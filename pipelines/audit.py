"""`make data-audit`: generate docs/DATA_GAPS.md and docs/DATA_SOURCES.md from code.

Inputs: data/audit/*.json (written by each fetcher), data/raw/*/MANIFEST.json, data/processed/*.csv.
Also verifies: every manifest entry's file exists with the recorded sha256; every processed CSV has
`provenance` and `source_manifest_id` columns with no blanks (exit code 1 otherwise).
"""
from __future__ import annotations

import json
import sys

import pandas as pd

from pipelines.common import AUDIT_DIR, PROCESSED, RAW, ROOT, sha256_file

STATUS_ORDER = ["MISSING", "RESTRICTED", "UNVERIFIED", "PARTIAL", "AVAILABLE"]
LICENCE_FLAGS = {"NON_COMMERCIAL_FREE_TIER", "ATTRIBUTION_REQUIRED", "SHARE_ALIKE_ODbL", "UCDAVIS_NO_COPY",
                 "LICENCE_UNVERIFIED"}
# Processed files that are derived geometry/reference tables without row-level provenance columns.
PROVENANCE_EXEMPT: set[str] = set()
NOT_COMMITTED_SUFFIXES = {".pbf", ".graphml", ".osm"}   # mirrors .gitignore


def load_records() -> dict[str, dict]:
    return {p.stem: json.loads(p.read_text(encoding="utf-8")) for p in sorted(AUDIT_DIR.glob("*.json"))}


def verify_manifests() -> tuple[list[dict], list[str]]:
    rows, errors = [], []
    for m in sorted(RAW.glob("*/MANIFEST.json")):
        man = json.loads(m.read_text(encoding="utf-8"))
        for e in man["entries"]:
            f = m.parent / e["file"]
            if not f.exists() and f.suffix in NOT_COMMITTED_SUFFIXES:
                # Large raw downloads are kept out of git (.gitignore); a clean clone simply has not fetched them yet.
                rows.append({"source": man["source"], "licence": man.get("licence", ""), "file": e["file"],
                             "manifest_id": e["manifest_id"], "url": e["url"], "fetched_at_utc": e["fetched_at_utc"],
                             "bytes": e["bytes"], "retrieval": e.get("retrieval", ""), "verified": None})
                continue
            ok = f.exists() and sha256_file(f) == e["sha256"]
            if not ok:
                errors.append(f"checksum/file mismatch: {f.relative_to(ROOT)}")
            rows.append({"source": man["source"], "licence": man.get("licence", ""), "file": e["file"],
                         "manifest_id": e["manifest_id"], "url": e["url"], "fetched_at_utc": e["fetched_at_utc"],
                         "bytes": e["bytes"], "retrieval": e.get("retrieval", ""), "verified": ok})
    return rows, errors


def verify_processed() -> tuple[list[dict], list[str]]:
    rows, errors = [], []
    for p in sorted(PROCESSED.glob("*.csv")):
        df = pd.read_csv(p, low_memory=False)
        has = {"provenance", "source_manifest_id"} <= set(df.columns)
        blanks = int(df[["provenance", "source_manifest_id"]].isna().any(axis=1).sum()) if has and len(df) else 0
        if p.name not in PROVENANCE_EXEMPT and (not has or blanks):
            errors.append(f"{p.name}: provenance columns missing or blank ({blanks} blank rows)")
        prov = df["provenance"].value_counts().to_dict() if has else {}
        rows.append({"file": p.name, "rows": len(df), "provenance": prov})
    return rows, errors


def md_escape(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def write_gaps(recs: dict[str, dict]) -> None:
    lines = ["# Data gaps", "",
             "_Auto-generated by `python tasks.py data-audit` (pipelines/audit.py). Do not edit by hand._", "",
             "Status key: AVAILABLE · PARTIAL · RESTRICTED · MISSING · UNVERIFIED. The UI shows "
             "\"Data unavailable\" for anything not AVAILABLE/PARTIAL; nothing is silently imputed.", "",
             "| Need | Source | Status | What was tried | Why it failed / gaps | Fallback used |",
             "|---|---|---|---|---|---|"]
    for _, r in sorted(recs.items(), key=lambda kv: (STATUS_ORDER.index(kv[1]["status"]), kv[0])):
        lines.append("| " + " | ".join(md_escape(x) for x in [
            r["need"], r["source_name"], f"**{r['status']}**", "<br>".join(r.get("tried", [])) or "-",
            r.get("why_failed") or "-", r.get("fallback") or "-"]) + " |")
    lines += ["", "## Generated files (not supplied)", "",
              "`nodes.csv` and `edges.csv` did not exist in the inputs; they are generated by `python tasks.py graph` "
              "from OSM + the Agmarknet market list (Phase 2, see GRAPH_BUILD.md).", "",
              "## Manual steps for the project owner", ""]
    manual = [r for r in recs.values() if {"MANUAL_STEP_REQUIRED", "API_KEY_REQUIRED"} & set(r.get("flags", []))]
    for r in manual:
        lines.append(f"- **{r['source_name']}**: {r.get('fallback', '')}")
    (ROOT / "docs" / "DATA_GAPS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_sources(recs: dict[str, dict], manifest_rows: list[dict], processed_rows: list[dict]) -> None:
    lines = ["# Data sources", "",
             "_Auto-generated by `python tasks.py data-audit` (pipelines/audit.py). Do not edit by hand._", "",
             "## Sources, access and licence", "",
             "| Source | Need | Status | Access | Auth | Licence / terms | Rate limits | Freshness | Known problems | Flags |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for _, r in sorted(recs.items()):
        lines.append("| " + " | ".join(md_escape(x) for x in [
            r["source_name"], r["need"], r["status"], r["access"], r["auth"], r["licence"],
            r.get("rate_limits") or "-", r.get("freshness") or "-", r.get("known_problems") or "-",
            ", ".join(r.get("flags", [])) or "-"]) + " |")
    flagged = sorted({(r["source_name"], f) for r in recs.values() for f in r.get("flags", []) if f in LICENCE_FLAGS})
    lines += ["", "## Licence flags to act on", ""] + [f"- {s}: `{f}`" for s, f in flagged]
    lines += ["", "## Coverage", ""] + [f"- **{r['source_name']}**: {md_escape(r['coverage'])}" for r in recs.values()]
    lines += ["", "## Raw files (immutable, checksummed)", "",
              "| Source | File | Manifest id | Retrieved (UTC) | Bytes | Method | Checksum verified |", "|---|---|---|---|---|---|---|"]
    for m in manifest_rows:
        lines.append(f"| {m['source']} | `{md_escape(m['file'])}` | `{m['manifest_id']}` | {m['fetched_at_utc']} | "
                     f"{m['bytes']:,} | {m['retrieval']} | {'yes' if m['verified'] else ('not cached (large, re-fetch with `make graph`)' if m['verified'] is None else '**NO**')} |")
    lines += ["", "## Processed tables", "", "| File | Rows | Provenance mix |", "|---|---|---|"]
    for p in processed_rows:
        lines.append(f"| `{p['file']}` | {p['rows']:,} | {p['provenance']} |")
    lines += ["", "## Values recalled from memory and not yet verified", "",
              "- data.gov.in mandi resource id `9ef84268-…` (needs an API key to verify).",
              "- Licence terms marked `UNVERIFIED` above."]
    (ROOT / "docs" / "DATA_SOURCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    recs = load_records()
    mrows, merr = verify_manifests()
    prows, perr = verify_processed()
    write_gaps(recs)
    write_sources(recs, mrows, prows)
    counts = pd.Series([r["status"] for r in recs.values()]).value_counts().to_dict()
    print(f"data-audit: {len(recs)} needs {counts}; {len(mrows)} raw files; {len(prows)} processed tables")
    for e in merr + perr:
        print("  ERROR", e)
    return 1 if (merr or perr) else 0


if __name__ == "__main__":
    sys.exit(main())
